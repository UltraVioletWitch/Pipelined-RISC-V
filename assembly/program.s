.section .text
.globl _start
.align 4

# ============================================================
# ENTRY
# ============================================================
_start:

    # --------------------------------------------------------
    # Stack setup (safe default)
    # --------------------------------------------------------
    li sp, 0x00007FFC

    # --------------------------------------------------------
    # GPIO setup
    # --------------------------------------------------------
    li t1, 0xF0000008
    li t0, 0x3FF
    sw t0, 0(t1)              # GPIO_DIR

    li t1, 0xF000000C
    li t0, 0xFC00
    sw t0, 0(t1)              # GPIO_IE

    # --------------------------------------------------------
    # UART interrupt enable
    # --------------------------------------------------------
    li t1, 0xF000100C
    li t0, 0x2
    sw t0, 0(t1)              # UART_IE

    # --------------------------------------------------------
    # Enable machine interrupts
    # --------------------------------------------------------
    li t0, (1 << 7) | (1 << 11)
    csrs mie, t0

    li t0, (1 << 3)
    csrs mstatus, t0

    # --------------------------------------------------------
    # Timer setup
    # --------------------------------------------------------
    li t1, 0xFFFF0008
    li t0, 0x100000
    sw t0, 0(t1)              # MTIMECMP_L

    # --------------------------------------------------------
    # UART TX test byte
    # --------------------------------------------------------
    li t1, 0xF0001000
    li t0, 0x41
    sw t0, 0(t1)

# ============================================================
# MAIN LOOP
# ============================================================
main_loop:

    # GPIO pattern
    li t1, 0xF0000004
    li t0, 0x155
    sw t0, 0(t1)

    # delay loop
    li t2, 50000

delay_loop:
    addi t2, t2, -1
    bnez t2, delay_loop

    j main_loop


# ============================================================
# INTERRUPT HANDLER
# ============================================================
.section .text.trap
.align 4
.globl trap_handler

trap_handler:

    csrr t0, mcause

    li t1, 0x80000007
    beq t0, t1, timer_irq

    li t1, 0x8000000B
    beq t0, t1, ext_irq

    mret


# ============================================================
# TIMER ISR
# ============================================================
timer_irq:

    li t1, 0xF0000004
    lw t2, 0(t1)
    xori t2, t2, 1
    sw t2, 0(t1)

    li t1, 0xFFFF0008
    li t3, 0x100000
    sw t3, 0(t1)

    mret


# ============================================================
# EXTERNAL ISR (UART / GPIO)
# ============================================================
ext_irq:

    # -----------------------------
    # UART IP check
    # -----------------------------
    li t1, 0xF0001008
    lw t2, 0(t1)

    andi t3, t2, 0x2
    beqz t3, gpio_irq

    # UART RX read
    li t1, 0xF0001004
    lw t4, 0(t1)

    # echo back
    li t1, 0xF0001000
    sw t4, 0(t1)

    # clear UART interrupt
    li t1, 0xF0001008
    li t5, 0x2
    sw t5, 0(t1)


gpio_irq:

    # clear GPIO interrupt
    li t1, 0xF000000C
    li t5, 0xFFFF
    sw t5, 0(t1)

    mret
